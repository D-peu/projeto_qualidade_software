package br.com.projeto_qualidade_software.projeto.persistence;

import org.flywaydb.core.Flyway;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;
import org.testcontainers.containers.PostgreSQLContainer;
import org.testcontainers.junit.jupiter.Container;
import org.testcontainers.junit.jupiter.Testcontainers;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.SQLException;
import java.sql.Statement;
import java.sql.Timestamp;
import java.time.Instant;
import java.time.LocalDateTime;
import java.util.HashSet;
import java.util.Set;

import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

@Testcontainers(disabledWithoutDocker = true)
class AlteracaoHorarioMigrationPostgresTest {

    @Container
    private static final PostgreSQLContainer<?> POSTGRES =
            new PostgreSQLContainer<>("postgres:16-alpine");

    @BeforeAll
    static void prepareExistingSchemaAndRunMigration() throws SQLException {
        try (Connection connection = openConnection();
             Statement statement = connection.createStatement()) {
            statement.execute("""
                    CREATE TABLE reservas (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
                    )
                    """);
            statement.execute("""
                    CREATE TABLE responsaveis (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
                    )
                    """);
        }

        Flyway flyway = Flyway.configure()
                .dataSource(POSTGRES.getJdbcUrl(), POSTGRES.getUsername(), POSTGRES.getPassword())
                .locations("classpath:db/migration")
                .baselineVersion("0")
                .load();
        flyway.baseline();
        flyway.migrate();
    }

    @Test
    void migrationCreatesConstrainedAppendOnlyAuditTableAndIndexes() throws SQLException {
        try (Connection connection = openConnection();
             Statement statement = connection.createStatement()) {
            statement.execute("INSERT INTO reservas DEFAULT VALUES");
            statement.execute("INSERT INTO responsaveis DEFAULT VALUES");
            insertAudit(
                    connection,
                    1,
                    1,
                    LocalDateTime.of(2026, 11, 12, 9, 0),
                    LocalDateTime.of(2026, 11, 12, 10, 0),
                    LocalDateTime.of(2026, 11, 12, 11, 0),
                    LocalDateTime.of(2026, 11, 12, 12, 0)
            );

            assertThrows(SQLException.class, () -> insertAudit(
                    connection,
                    1,
                    1,
                    LocalDateTime.of(2026, 11, 12, 10, 0),
                    LocalDateTime.of(2026, 11, 12, 9, 0),
                    LocalDateTime.of(2026, 11, 12, 11, 0),
                    LocalDateTime.of(2026, 11, 12, 12, 0)
            ));
            assertThrows(SQLException.class, () -> insertAudit(
                    connection,
                    1,
                    1,
                    LocalDateTime.of(2026, 11, 12, 9, 0),
                    LocalDateTime.of(2026, 11, 12, 10, 0),
                    LocalDateTime.of(2026, 11, 12, 11, 0),
                    LocalDateTime.of(2026, 11, 12, 10, 0)
            ));
            assertThrows(SQLException.class, () -> insertAudit(
                    connection,
                    1,
                    1,
                    LocalDateTime.of(2026, 11, 12, 9, 0),
                    LocalDateTime.of(2026, 11, 12, 10, 0),
                    LocalDateTime.of(2026, 11, 12, 9, 0),
                    LocalDateTime.of(2026, 11, 12, 10, 0)
            ));
            assertThrows(SQLException.class, () -> insertAudit(
                    connection,
                    999,
                    1,
                    LocalDateTime.of(2026, 11, 12, 9, 0),
                    LocalDateTime.of(2026, 11, 12, 10, 0),
                    LocalDateTime.of(2026, 11, 12, 11, 0),
                    LocalDateTime.of(2026, 11, 12, 12, 0)
            ));
            assertThrows(SQLException.class, () -> insertAudit(
                    connection,
                    1,
                    999,
                    LocalDateTime.of(2026, 11, 12, 9, 0),
                    LocalDateTime.of(2026, 11, 12, 10, 0),
                    LocalDateTime.of(2026, 11, 12, 11, 0),
                    LocalDateTime.of(2026, 11, 12, 12, 0)
            ));
            assertThrows(SQLException.class, () -> statement.executeUpdate(
                    "UPDATE alteracoes_horario_aplicadas SET new_fim = new_fim"
            ));
            assertThrows(SQLException.class, () -> statement.executeUpdate(
                    "DELETE FROM alteracoes_horario_aplicadas"
            ));
            assertThrows(SQLException.class, () -> statement.execute("TRUNCATE alteracoes_horario_aplicadas"));
            assertThrows(SQLException.class, () -> statement.executeUpdate("DELETE FROM reservas"));
            assertThrows(SQLException.class, () -> statement.executeUpdate("DELETE FROM responsaveis"));

            Set<String> indexes = new HashSet<>();
            try (var result = statement.executeQuery("""
                    SELECT indexname
                    FROM pg_indexes
                    WHERE tablename = 'alteracoes_horario_aplicadas'
                    """)) {
                while (result.next()) {
                    indexes.add(result.getString(1));
                }
            }
            assertTrue(indexes.contains("idx_alteracoes_horario_aplicadas_history"));
            assertTrue(indexes.contains("idx_alteracoes_horario_aplicadas_actor"));
        }
    }

    private static void insertAudit(
            Connection connection,
            long reservaId,
            long responsavelId,
            LocalDateTime oldInicio,
            LocalDateTime oldFim,
            LocalDateTime newInicio,
            LocalDateTime newFim
    ) throws SQLException {
        try (PreparedStatement statement = connection.prepareStatement("""
                INSERT INTO alteracoes_horario_aplicadas
                    (reserva_id, responsavel_id, old_inicio, old_fim, new_inicio, new_fim, applied_at)
                VALUES (?, ?, ?, ?, ?, ?, ?)
                """)) {
            statement.setLong(1, reservaId);
            statement.setLong(2, responsavelId);
            statement.setTimestamp(3, Timestamp.valueOf(oldInicio));
            statement.setTimestamp(4, Timestamp.valueOf(oldFim));
            statement.setTimestamp(5, Timestamp.valueOf(newInicio));
            statement.setTimestamp(6, Timestamp.valueOf(newFim));
            statement.setTimestamp(7, Timestamp.from(Instant.parse("2026-11-12T11:00:00Z")));
            statement.executeUpdate();
        }
    }

    private static Connection openConnection() throws SQLException {
        return DriverManager.getConnection(
                POSTGRES.getJdbcUrl(),
                POSTGRES.getUsername(),
                POSTGRES.getPassword()
        );
    }
}
