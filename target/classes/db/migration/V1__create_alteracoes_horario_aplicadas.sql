-- Manual precondition: this migration assumes inspected, compatible reservas(id)
-- and responsaveis(id) tables with BIGINT primary keys already exist. For any
-- pre-existing database, inventory and reconcile its schema/history, then
-- establish an explicitly reviewed Flyway baseline before enabling migration.
-- Do not infer a clean schema or use automatic baselining from this migration.

CREATE TABLE alteracoes_horario_aplicadas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id BIGINT NOT NULL,
    responsavel_id BIGINT NOT NULL,
    old_inicio TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    old_fim TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    new_inicio TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    new_fim TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    applied_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_alteracoes_horario_aplicadas_reserva
        FOREIGN KEY (reserva_id) REFERENCES reservas (id) ON DELETE RESTRICT,
    CONSTRAINT fk_alteracoes_horario_aplicadas_responsavel
        FOREIGN KEY (responsavel_id) REFERENCES responsaveis (id) ON DELETE RESTRICT,
    CONSTRAINT ck_alteracoes_horario_aplicadas_old_interval
        CHECK (old_fim > old_inicio),
    CONSTRAINT ck_alteracoes_horario_aplicadas_new_interval
        CHECK (new_fim > new_inicio),
    CONSTRAINT ck_alteracoes_horario_aplicadas_not_noop
        CHECK (old_inicio <> new_inicio OR old_fim <> new_fim)
);

CREATE INDEX idx_alteracoes_horario_aplicadas_history
    ON alteracoes_horario_aplicadas (reserva_id, applied_at, id);

CREATE INDEX idx_alteracoes_horario_aplicadas_actor
    ON alteracoes_horario_aplicadas (responsavel_id);

CREATE FUNCTION impedir_mutacao_alteracoes_horario_aplicadas()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'alteracoes_horario_aplicadas is append-only';
END;
$$;

CREATE TRIGGER trg_alteracoes_horario_aplicadas_immutable
    BEFORE UPDATE OR DELETE ON alteracoes_horario_aplicadas
    FOR EACH ROW
    EXECUTE FUNCTION impedir_mutacao_alteracoes_horario_aplicadas();

CREATE TRIGGER trg_alteracoes_horario_aplicadas_no_truncate
    BEFORE TRUNCATE ON alteracoes_horario_aplicadas
    FOR EACH STATEMENT
    EXECUTE FUNCTION impedir_mutacao_alteracoes_horario_aplicadas();
