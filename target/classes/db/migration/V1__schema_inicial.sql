CREATE TABLE salas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    capacidade INTEGER NOT NULL CHECK (capacidade >= 20),
    status_sala VARCHAR(32) NOT NULL
);

CREATE TABLE responsaveis (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    criado_em DATE,
    atualizado_em DATE
);

CREATE TABLE solicitantes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    email VARCHAR(255),
    password VARCHAR(255),
    tipo_solicitante VARCHAR(32) NOT NULL,
    criado_em DATE,
    atualizado_em DATE
);

CREATE TABLE reservas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sala_id BIGINT NOT NULL REFERENCES salas (id),
    solicitante_id BIGINT NOT NULL REFERENCES solicitantes (id),
    responsavel_id BIGINT REFERENCES responsaveis (id),
    inicio TIMESTAMP NOT NULL,
    fim TIMESTAMP NOT NULL,
    status VARCHAR(32) NOT NULL,
    solicitado_em TIMESTAMP NOT NULL,
    aprovado_em TIMESTAMP,
    CONSTRAINT ck_reservas_intervalo CHECK (fim > inicio)
);
